std::optional<std::uintptr_t> FindOriginalSoundGlobalRva(const std::string_view symbol) {
    const std::string normalized = NormalizeAudioId(symbol);
    for (const auto& [name, rva] : kSounds) {
        if (name == normalized) return rva;
    }
    return std::nullopt;
}

bool IsKnownOriginalSound(const std::string_view symbol) {
    return FindOriginalSoundGlobalRva(symbol).has_value();
}

